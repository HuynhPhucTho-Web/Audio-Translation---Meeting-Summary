/**
 * Helper hook / accessor to get localized string with safe fallback
 */
export function getTranslation(lang = 'vi', path = '') {
  const dictionary = TRANSLATIONS[lang] || TRANSLATIONS.vi;
  const keys = path.split('.');
  let current = dictionary;
  for (const k of keys) {
    if (current && typeof current === 'object' && k in current) {
      current = current[k];
    } else {
      // Fallback to Vietnamese, then English
      let fallback = TRANSLATIONS.vi;
      for (const fbKey of keys) {
        if (fallback && typeof fallback === 'object' && fbKey in fallback) {
          fallback = fallback[fbKey];
        } else {
          fallback = null;
          break;
        }
      }
      return fallback || path;
    }
  }
  return current;
}
